//! App text is written in Spanish (the keys) and translated to English, like the macOS app.
//! Dialogs provided by GTK follow the system language.

use std::cell::Cell;
use std::collections::HashMap;
use std::sync::LazyLock;

thread_local! {
    static SPANISH: Cell<bool> = const { Cell::new(false) };
}

/// Resolves "system", "en" or "es" to the language the app shows.
pub fn resolve(selection: &str) -> &'static str {
    match selection {
        "en" => "en",
        "es" => "es",
        _ => {
            let preferred = ["LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"]
                .iter()
                .filter_map(|k| std::env::var(k).ok())
                .find(|v| !v.is_empty())
                .unwrap_or_default();
            let spanish = preferred
                .split(':')
                .map(|l| l.to_lowercase())
                .find(|l| l.starts_with("es") || l.starts_with("en"))
                .is_some_and(|l| l.starts_with("es"));
            if spanish { "es" } else { "en" }
        }
    }
}

pub fn set_language(code: &str) {
    SPANISH.with(|s| s.set(code == "es"));
}

pub fn language() -> &'static str {
    if SPANISH.with(|s| s.get()) { "es" } else { "en" }
}

pub fn t(key: &str) -> String {
    if SPANISH.with(|s| s.get()) {
        return key.to_string();
    }
    ENGLISH.get(key).map_or_else(|| key.to_string(), |v| v.to_string())
}

/// Translates and fills `%@` / `%d` placeholders in order.
pub fn tf(key: &str, values: &[&str]) -> String {
    let mut text = t(key);
    for value in values {
        if let Some(pos) = text.find("%@").or_else(|| text.find("%d")) {
            text.replace_range(pos..pos + 2, value);
        }
    }
    text
}

