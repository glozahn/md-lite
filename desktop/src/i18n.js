let language = 'es';

export function resolveLanguage(setting) {
  if (setting === 'es' || setting === 'en') return setting;
  const preferred = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  for (const tag of preferred) {
    const code = tag.toLowerCase().split(/[-_]/)[0];
    if (code === 'es' || code === 'en') return code;
  }
  return 'en';
}

export function setLanguage(value) { language = value; document.documentElement.lang = value; }
export function currentLanguage() { return language; }

export function t(key, ...values) {
  let text = language === 'es' ? key : (english[key] ?? key);
  for (const value of values) text = text.replace(/%[sd]/, String(value));
  return text;
}
